-- ============================================================
-- Donations + message wall (2026-11-25)
--
-- Flow: donor pays with the QR code, then submits amount / nickname / message.
-- The row stays 'pending' until an admin confirms it in /admin/donations.
-- Plain messages (kind = 'message') are published immediately; admins can hide them.
-- No direct table access: everything goes through the RPCs below.
-- ============================================================

-- Registry: allow 'domain' entries (Domains page).
alter table public.admin_resources drop constraint if exists admin_resources_kind_check;
alter table public.admin_resources add constraint admin_resources_kind_check
  check (kind in ('integration', 'mcp_server', 'secret', 'workflow', 'agent', 'domain'));

create table if not exists public.donations (
  id bigint generated by default as identity primary key,
  public_id text not null unique default upper(substr(md5(gen_random_uuid()::text), 1, 6)),
  kind text not null default 'donation' check (kind in ('donation', 'message')),
  user_id uuid references auth.users (id) on delete set null,
  display_name text,
  anonymous boolean not null default false,
  amount numeric(12, 2),
  currency text check (currency in ('CNY', 'USD')),
  method text check (method in ('wechat', 'alipay', 'paypal', 'other')),
  message text,
  reference text,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'rejected', 'hidden')),
  visitor_id text,
  ip text,
  user_agent text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by text,
  check (kind = 'message' or (amount is not null and amount > 0 and currency is not null))
);

create index if not exists donations_status_created_idx on public.donations (status, created_at desc);
alter table public.donations enable row level security;

drop policy if exists "donations_read_admin" on public.donations;
create policy "donations_read_admin"
  on public.donations for select
  using (public.is_admin());

-- USD → CNY rate used only to rank the top 3 across currencies.
create or replace function public._donation_cny(p_amount numeric, p_currency text)
returns numeric
language sql
immutable
as $$
  select case when p_currency = 'USD' then p_amount * 7.2 else coalesce(p_amount, 0) end;
$$;

create or replace function public.submit_donation(
  p_kind text,
  p_name text,
  p_anonymous boolean,
  p_amount numeric,
  p_currency text,
  p_method text,
  p_message text,
  p_reference text,
  p_visitor text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_ip text := left(public._req_ip(), 64);
  v_kind text := case when p_kind = 'message' then 'message' else 'donation' end;
  v_name text := nullif(left(trim(coalesce(p_name, '')), 40), '');
  v_message text := nullif(left(trim(coalesce(p_message, '')), 300), '');
  v_row public.donations;
begin
  if v_ip is not null and (select count(*) from public.donations
                             where ip = v_ip and created_at > now() - interval '1 hour') >= 6 then
    raise exception 'Too many submissions from this network. Please try again later.' using errcode = 'P0001';
  end if;

  if v_kind = 'message' and v_message is null then
    raise exception 'Write a message first.' using errcode = 'P0001';
  end if;

  if v_kind = 'donation' then
    if p_amount is null or p_amount < 0.01 or p_amount > 100000 then
      raise exception 'Enter an amount between 0.01 and 100000.' using errcode = 'P0001';
    end if;
    if p_currency not in ('CNY', 'USD') then
      raise exception 'Unsupported currency.' using errcode = 'P0001';
    end if;
  end if;

  if v_name is null and auth.uid() is not null then
    select nullif(display_name, '') into v_name from public.profiles where id = auth.uid();
  end if;

  insert into public.donations (
    kind, user_id, display_name, anonymous, amount, currency, method, message, reference,
    status, visitor_id, ip, user_agent
  ) values (
    v_kind,
    auth.uid(),
    v_name,
    coalesce(p_anonymous, false),
    case when v_kind = 'donation' then round(p_amount, 2) end,
    case when v_kind = 'donation' then p_currency end,
    case when v_kind = 'donation' and p_method in ('wechat', 'alipay', 'paypal', 'other') then p_method end,
    v_message,
    nullif(left(trim(coalesce(p_reference, '')), 80), ''),
    case when v_kind = 'message' then 'confirmed' else 'pending' end,
    nullif(left(p_visitor, 64), ''),
    v_ip,
    left(public._req_header('user-agent'), 400)
  )
  returning * into v_row;

  return jsonb_build_object('public_id', v_row.public_id, 'status', v_row.status, 'kind', v_row.kind);
end;
$$;

-- Public wall: stats, recent confirmed entries, 30-day top 3. No IPs, no emails.
create or replace function public.donation_wall(p_limit int default 30)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  with confirmed as (
    select * from public.donations where status = 'confirmed'
  ),
  money as (
    select * from confirmed where kind = 'donation'
  ),
  month as (
    select * from money where created_at >= now() - interval '30 days'
  ),
  donors as (
    -- One donor = signed-in account, else the same public nickname; anonymous gifts stay separate.
    select case
             when anonymous then 'anon:' || id
             when user_id is not null then 'u:' || user_id
             when display_name is not null then 'n:' || lower(display_name)
             else 'anon:' || id
           end as donor_key,
           *
      from month
  ),
  ranked as (
    select donor_key,
           bool_or(anonymous) as anonymous,
           (array_agg(display_name order by created_at desc))[1] as display_name,
           sum(case when currency = 'CNY' then amount else 0 end) as cny,
           sum(case when currency = 'USD' then amount else 0 end) as usd,
           sum(public._donation_cny(amount, currency)) as cny_equiv,
           count(*) as gifts,
           max(created_at) as last_at
      from donors
     group by donor_key
     order by cny_equiv desc, last_at asc
     limit 3
  )
  select jsonb_build_object(
    'stats', jsonb_build_object(
      'donors_30d', (select count(distinct donor_key) from donors),
      'gifts_30d', (select count(*) from month),
      'cny_30d', (select coalesce(sum(amount), 0) from month where currency = 'CNY'),
      'usd_30d', (select coalesce(sum(amount), 0) from month where currency = 'USD'),
      'gifts_all', (select count(*) from money),
      'cny_all', (select coalesce(sum(amount), 0) from money where currency = 'CNY'),
      'usd_all', (select coalesce(sum(amount), 0) from money where currency = 'USD'),
      'messages', (select count(*) from confirmed where message is not null)
    ),
    'top', coalesce((
      select jsonb_agg(jsonb_build_object(
               'name', case when anonymous then null else display_name end,
               'cny', cny, 'usd', usd, 'cny_equiv', round(cny_equiv, 2),
               'gifts', gifts, 'last_at', last_at
             ) order by cny_equiv desc, last_at asc)
        from ranked), '[]'::jsonb),
    'recent', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', public_id,
               'kind', kind,
               'name', case when anonymous then null else display_name end,
               'amount', amount,
               'currency', currency,
               'method', method,
               'message', message,
               'at', created_at
             ) order by created_at desc)
        from (select * from confirmed order by created_at desc
               limit greatest(1, least(coalesce(p_limit, 30), 100))) r), '[]'::jsonb),
    'generated_at', now()
  );
$$;

-- Admin: list + review
create or replace function public.admin_donations(p_status text default null, p_limit int default 200)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_items jsonb;
begin
  perform public._admin_guard();
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', d.id, 'public_id', d.public_id, 'kind', d.kind,
           'user_id', d.user_id, 'email', p.email, 'display_name', d.display_name,
           'anonymous', d.anonymous, 'amount', d.amount, 'currency', d.currency,
           'method', d.method, 'message', d.message, 'reference', d.reference,
           'status', d.status, 'ip', d.ip, 'user_agent', d.user_agent, 'visitor_id', d.visitor_id,
           'created_at', d.created_at, 'reviewed_at', d.reviewed_at, 'reviewed_by', d.reviewed_by
         ) order by d.created_at desc), '[]'::jsonb)
    into v_items
    from (select * from public.donations
           where p_status is null or status = p_status
           order by created_at desc
           limit greatest(1, least(coalesce(p_limit, 200), 1000))) d
    left join public.profiles p on p.id = d.user_id;

  return jsonb_build_object(
    'items', v_items,
    'total', jsonb_array_length(v_items),
    'pending', (select count(*) from public.donations where status = 'pending'),
    'generated_at', now()
  );
end;
$$;

create or replace function public.admin_donation_review(p_id bigint, p_status text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_row public.donations;
begin
  perform public._admin_guard();
  if p_status not in ('pending', 'confirmed', 'rejected', 'hidden') then
    raise exception 'invalid status';
  end if;
  update public.donations
     set status = p_status, reviewed_at = now(), reviewed_by = auth.jwt() ->> 'email'
   where id = p_id
  returning * into v_row;
  if v_row.id is null then
    raise exception 'donation not found';
  end if;
  perform public._admin_audit('donation.' || p_status, v_row.public_id,
    jsonb_build_object('amount', v_row.amount, 'currency', v_row.currency, 'kind', v_row.kind));
  return to_jsonb(v_row);
end;
$$;

