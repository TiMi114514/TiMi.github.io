-- ============================================================
-- Outage alerts by email (2026-11-26)
--
-- A watcher runs INSIDE Supabase every minute (pg_cron), so it still works
-- when the home PC, its internet or its power is down.
--
-- Checks (each one is an "alert key"):
--   host:<id>            monitor host has not reported for > 3 minutes
--   service:<host>:<svc> a service in the latest sample is not ok
--   resource:<host>:cpu|mem|disk  >= 95 % for 3 consecutive samples
--   public:funnel        public gateway URL does not answer {"ok":true} (pg_net probe)
--
-- Lifecycle: an alert opens after 2 consecutive failing checks (no flapping),
-- emails the admins once, re-reminds every 6 hours while still open, and sends
-- one "recovered" email when it clears. Email goes out via Resend; the API key
-- lives encrypted in Supabase Vault (secret name: resend_api_key).
-- ============================================================

create extension if not exists pg_net;
create extension if not exists pg_cron;

create table if not exists public.alert_state (
  key text primary key,
  status text not null default 'ok' check (status in ('ok', 'pending', 'open')),
  fail_count int not null default 0,
  summary text,
  detail jsonb not null default '{}'::jsonb,
  opened_at timestamptz,
  last_failed_at timestamptz,
  last_notified_at timestamptz,
  resolved_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.alert_events (
  id bigint generated by default as identity primary key,
  key text not null,
  kind text not null check (kind in ('opened', 'reminder', 'resolved', 'test')),
  summary text,
  detail jsonb not null default '{}'::jsonb,
  email_request_id bigint,
  email_status text,
  created_at timestamptz not null default now()
);
create index if not exists alert_events_created_idx on public.alert_events (created_at desc);

-- Public gateway probes (pg_net is async: request now, read the result next minute).
create table if not exists public.alert_probes (
  id bigint generated by default as identity primary key,
  target text not null,
  request_id bigint not null,
  created_at timestamptz not null default now()
);

alter table public.alert_state enable row level security;
alter table public.alert_events enable row level security;
alter table public.alert_probes enable row level security;
drop policy if exists "alert_state_admin" on public.alert_state;
create policy "alert_state_admin" on public.alert_state for select using (public.is_admin());
drop policy if exists "alert_events_admin" on public.alert_events;
create policy "alert_events_admin" on public.alert_events for select using (public.is_admin());

