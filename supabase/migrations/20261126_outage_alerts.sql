-- ---------------------------------------------------------------- email
create or replace function public._alert_send(p_subject text, p_text text)
returns bigint
language plpgsql
volatile
security definer
set search_path = public, extensions, vault
as $$
declare
  v_cfg jsonb := (select value from public.site_settings where key = 'alerts.config');
  v_key text := (select decrypted_secret from vault.decrypted_secrets where name = 'resend_api_key' limit 1);
  v_id bigint;
begin
  if v_key is null or v_cfg is null or coalesce((v_cfg ->> 'enabled')::boolean, true) = false then
    return null;  -- no provider configured yet: alert is still recorded in alert_events
  end if;
  select net.http_post(
    url := 'https://api.resend.com/emails',
    headers := jsonb_build_object('Authorization', 'Bearer ' || v_key, 'Content-Type', 'application/json'),
    body := jsonb_build_object(
      'from', coalesce(v_cfg ->> 'from', 'A-Level Hub Alerts <onboarding@resend.dev>'),
      'to', v_cfg -> 'recipients',
      'subject', p_subject,
      'text', p_text
    ),
    timeout_milliseconds := 15000
  ) into v_id;
  return v_id;
end;
$$;

create or replace function public._alert_notify(p_key text, p_kind text, p_summary text, p_detail jsonb)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_subject text;
  v_body text;
  v_req bigint;
begin
  v_subject := case p_kind
    when 'opened'   then '[A-Level Hub] DOWN: '
    when 'reminder' then '[A-Level Hub] STILL DOWN: '
    when 'resolved' then '[A-Level Hub] RECOVERED: '
    else '[A-Level Hub] TEST: ' end || p_summary;
  v_body := p_summary || E'\n\n'
    || 'Alert: ' || p_key || E'\n'
    || 'Time (Beijing): ' || to_char(now() at time zone 'Asia/Shanghai', 'YYYY-MM-DD HH24:MI:SS') || E'\n'
    || case when p_detail <> '{}'::jsonb then 'Details: ' || p_detail::text || E'\n' else '' end
    || E'\nWhat to check:\n'
    || case
         when p_key like 'host:%' then '- Is the home PC on, awake and online? Run D:\start-alevelhub.cmd status' || E'\n'
         when p_key like 'service:%' then '- A container or the gateway is unhealthy. Run D:\start-alevelhub.cmd (restarts the stack).' || E'\n'
         when p_key like 'public:%' then '- The public Funnel URL is unreachable. Check Tailscale Funnel on the PC, then D:\start-alevelhub.cmd status' || E'\n'
         when p_key like 'resource:%' then '- A resource is near its limit. See Admin > Servers.' || E'\n'
         else '' end
    || 'Dashboard: https://timi114514.github.io/TiMi.github.io/admin/servers/' || E'\n';
  v_req := public._alert_send(v_subject, v_body);
  insert into public.alert_events (key, kind, summary, detail, email_request_id, email_status)
  values (p_key, p_kind, p_summary, coalesce(p_detail, '{}'::jsonb), v_req, case when v_req is null then 'not_configured' else 'queued' end);
end;
$$;

-- Record one check result and drive the alert lifecycle.
create or replace function public._alert_observe(p_key text, p_failing boolean, p_summary text, p_detail jsonb default '{}'::jsonb)
returns void
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_cfg jsonb := (select value from public.site_settings where key = 'alerts.config');
  v_confirm int := coalesce((v_cfg ->> 'confirm_checks')::int, 2);
  v_remind interval := make_interval(hours => coalesce((v_cfg ->> 'reminder_hours')::int, 6));
  s public.alert_state;
begin
  insert into public.alert_state (key) values (p_key) on conflict (key) do nothing;
  select * into s from public.alert_state where key = p_key for update;

  if p_failing then
    s.fail_count := s.fail_count + 1;
    s.last_failed_at := now();
    s.summary := p_summary;
    s.detail := coalesce(p_detail, '{}'::jsonb);
    if s.status = 'open' then
      if s.last_notified_at < now() - v_remind then
        perform public._alert_notify(p_key, 'reminder', p_summary, p_detail);
        s.last_notified_at := now();
      end if;
    elsif s.fail_count >= v_confirm then
      s.status := 'open';
      s.opened_at := now();
      s.resolved_at := null;
      perform public._alert_notify(p_key, 'opened', p_summary, p_detail);
      s.last_notified_at := now();
    else
      s.status := 'pending';
    end if;
  else
    if s.status = 'open' then
      perform public._alert_notify(p_key, 'resolved',
        coalesce(s.summary, p_key) || ' — back to normal after ' ||
        to_char(now() - s.opened_at, 'HH24"h "MI"m"'), '{}'::jsonb);
      s.resolved_at := now();
    end if;
    s.status := 'ok';
    s.fail_count := 0;
  end if;

  update public.alert_state
     set status = s.status, fail_count = s.fail_count, summary = s.summary, detail = s.detail,
         opened_at = s.opened_at, last_failed_at = s.last_failed_at,
         last_notified_at = s.last_notified_at, resolved_at = s.resolved_at, updated_at = now()
   where key = p_key;
end;
$$;

-- ---------------------------------------------------------------- the watcher
create or replace function public.alert_watch()
returns void
language plpgsql
volatile
security definer
set search_path = public, extensions
as $$
declare
  v_cfg jsonb := (select value from public.site_settings where key = 'alerts.config');
  v_stale interval := make_interval(mins => coalesce((v_cfg ->> 'host_stale_minutes')::int, 3));
  v_pct numeric := coalesce((v_cfg ->> 'resource_pct')::numeric, 95);
  h record;
  m record;
  svc jsonb;
  d jsonb;
  v_probe record;
  v_resp record;
  v_ok boolean;
  v_hot int;
begin
  if coalesce((v_cfg ->> 'enabled')::boolean, true) = false then return; end if;

  -- 1. Hosts that stopped reporting.
  for h in select id, name, last_seen from public.monitor_hosts loop
    perform public._alert_observe(
      'host:' || h.id,
      h.last_seen is null or h.last_seen < now() - v_stale,
      h.name || ' has stopped reporting (last seen ' ||
        coalesce(to_char(h.last_seen at time zone 'Asia/Shanghai', 'MM-DD HH24:MI'), 'never') || ' Beijing time)',
      jsonb_build_object('last_seen', h.last_seen));

    -- 2. Services + resources, only judged when the host is reporting.
    select * into m from public.host_metrics where host_id = h.id order by at desc limit 1;
    if m.at is not null and m.at > now() - v_stale then
      for svc in select * from jsonb_array_elements(coalesce(m.services, '[]'::jsonb)) loop
        perform public._alert_observe(
          'service:' || h.id || ':' || (svc ->> 'name'),
          coalesce((svc ->> 'ok')::boolean, false) = false,
          h.name || ': ' || replace(svc ->> 'name', 'docker:docker-', '') || ' is down (' || coalesce(svc ->> 'detail', '?') || ')',
          svc);
      end loop;

      select count(*) into v_hot from (select cpu_pct from public.host_metrics where host_id = h.id order by at desc limit 3) x where cpu_pct >= v_pct;
      perform public._alert_observe('resource:' || h.id || ':cpu', v_hot = 3, h.name || ': CPU above ' || v_pct || '% for 3 samples', jsonb_build_object('cpu_pct', m.cpu_pct));
      select count(*) into v_hot from (select mem_used, mem_total from public.host_metrics where host_id = h.id order by at desc limit 3) x where mem_total > 0 and 100.0 * mem_used / mem_total >= v_pct;
      perform public._alert_observe('resource:' || h.id || ':mem', v_hot = 3, h.name || ': memory above ' || v_pct || '% for 3 samples', jsonb_build_object('mem_used', m.mem_used, 'mem_total', m.mem_total));
      v_ok := true;
      for d in select * from jsonb_array_elements(coalesce(m.disk, '[]'::jsonb)) loop
        if (d ->> 'total')::numeric > 0 and 100.0 * (d ->> 'used')::numeric / (d ->> 'total')::numeric >= v_pct then
          v_ok := false;
        end if;
      end loop;
      perform public._alert_observe('resource:' || h.id || ':disk', not v_ok, h.name || ': a disk is above ' || v_pct || '% full', jsonb_build_object('disk', m.disk));
    end if;
  end loop;

  -- 3. Public gateway: read last minute's probe, then fire a new one.
  select * into v_probe from public.alert_probes where target = 'funnel' order by id desc limit 1;
  if v_probe.id is not null and v_probe.created_at < now() - interval '20 seconds' then
    select status_code, content, timed_out, error_msg into v_resp from net._http_response where id = v_probe.request_id;
    if found then
      perform public._alert_observe('public:funnel',
        not (v_resp.status_code = 200 and coalesce(v_resp.content, '') like '%"ok":true%'),
        'Public RAGFlow gateway is unreachable (past papers / AI tutor down for visitors)',
        jsonb_build_object('status', v_resp.status_code, 'timed_out', v_resp.timed_out, 'error', v_resp.error_msg, 'body', left(coalesce(v_resp.content, ''), 200)));
    end if;
  end if;
  insert into public.alert_probes (target, request_id)
  select 'funnel', net.http_get(url := v_cfg ->> 'public_url', timeout_milliseconds := 15000)
   where v_cfg ->> 'public_url' is not null;

  -- 4. Record email delivery results, keep tables small.
  update public.alert_events e
     set email_status = case when r.status_code between 200 and 299 then 'sent' else 'failed ' || coalesce(r.status_code::text, r.error_msg, '?') end
    from net._http_response r
   where e.email_request_id = r.id and e.email_status = 'queued';
  delete from public.alert_probes where created_at < now() - interval '1 day';
  delete from public.alert_events where created_at < now() - interval '180 days';
end;
$$;

-- ---------------------------------------------------------------- admin API
create or replace function public.admin_alerts()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, vault
as $$
begin
  perform public._admin_guard();
  return jsonb_build_object(
    'config', (select value from public.site_settings where key = 'alerts.config'),
    'email_configured', exists (select 1 from vault.secrets where name = 'resend_api_key'),
    'watcher_scheduled', exists (select 1 from cron.job where jobname = 'alert-watch' and active),
    'open', coalesce((select jsonb_agg(to_jsonb(s) order by s.opened_at desc) from public.alert_state s where s.status = 'open'), '[]'::jsonb),
    'pending', coalesce((select jsonb_agg(to_jsonb(s)) from public.alert_state s where s.status = 'pending'), '[]'::jsonb),
    'events', coalesce((select jsonb_agg(to_jsonb(e) order by e.created_at desc) from (select * from public.alert_events order by created_at desc limit 100) e), '[]'::jsonb),
    'generated_at', now()
  );
end;
$$;

create or replace function public.admin_alert_test()
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
begin
  perform public._admin_guard();
  perform public._alert_notify('test', 'test', 'Test alert from the admin console — email delivery works',
    jsonb_build_object('requested_by', auth.jwt() ->> 'email'));
  perform public._admin_audit('alerts.test', null, '{}'::jsonb);
  return (select to_jsonb(e) from public.alert_events e where key = 'test' order by id desc limit 1);
end;
$$;

create or replace function public.admin_alert_config(p_value jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v jsonb := (select value from public.site_settings where key = 'alerts.config') || coalesce(p_value, '{}'::jsonb);
begin
  perform public._admin_guard();
  if jsonb_typeof(v -> 'recipients') <> 'array' or jsonb_array_length(v -> 'recipients') = 0 then
    raise exception 'at least one recipient is required';
  end if;
  update public.site_settings set value = v, updated_by = auth.jwt() ->> 'email', updated_at = now() where key = 'alerts.config';
  perform public._admin_audit('alerts.config', null, '{}'::jsonb);
  return v;
end;
$$;

