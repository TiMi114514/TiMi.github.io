-- ============================================================
-- Host monitoring (2026-11-25)
--
-- Monitoring agents (the RAGFlow gateway on the home PC, later the Tencent
-- server) push a metrics sample every 30 s with a per-host ingest token.
-- The static site cannot read the host itself, so this table is the bridge.
-- Retention: raw samples 7 days.
-- ============================================================

create extension if not exists pgcrypto;

create table if not exists public.monitor_hosts (
  id text primary key check (id ~ '^[a-z0-9][a-z0-9._-]{0,40}$'),
  name text not null,
  role text,
  token_hash text not null,
  created_at timestamptz not null default now(),
  last_seen timestamptz,
  info jsonb not null default '{}'::jsonb
);

create table if not exists public.host_metrics (
  id bigint generated by default as identity primary key,
  host_id text not null references public.monitor_hosts (id) on delete cascade,
  at timestamptz not null default now(),
  cpu_pct real,
  load1 real,
  mem_total bigint,
  mem_used bigint,
  mem_available bigint,
  swap_total bigint,
  swap_used bigint,
  disk jsonb,          -- [{ mount, total, used, free }]
  net_rx_bps real,
  net_tx_bps real,
  connections jsonb,   -- { established, listen, time_wait, total }
  services jsonb,      -- [{ name, ok, ms, detail }]
  uptime_s bigint
);
create index if not exists host_metrics_host_at_idx on public.host_metrics (host_id, at desc);

alter table public.monitor_hosts enable row level security;
alter table public.host_metrics enable row level security;

drop policy if exists "monitor_hosts_admin" on public.monitor_hosts;
create policy "monitor_hosts_admin" on public.monitor_hosts for select using (public.is_admin());
drop policy if exists "host_metrics_admin" on public.host_metrics;
create policy "host_metrics_admin" on public.host_metrics for select using (public.is_admin());

-- Agent ingest: authenticated by a per-host token (only its SHA-256 is stored).
create or replace function public.ingest_host_metrics(p_host text, p_token text, p_sample jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public, extensions
as $$
declare
  v_host public.monitor_hosts;
  v_s jsonb := coalesce(p_sample, '{}'::jsonb);
begin
  select * into v_host from public.monitor_hosts where id = p_host;
  if v_host.id is null or v_host.token_hash <> encode(digest(coalesce(p_token, ''), 'sha256'), 'hex') then
    raise exception 'unknown host or bad token' using errcode = '42501';
  end if;

  -- At most one sample every 10 s per host.
  if exists (select 1 from public.host_metrics where host_id = p_host and at > now() - interval '10 seconds') then
    return jsonb_build_object('ok', true, 'skipped', true);
  end if;

  insert into public.host_metrics (
    host_id, cpu_pct, load1, mem_total, mem_used, mem_available, swap_total, swap_used,
    disk, net_rx_bps, net_tx_bps, connections, services, uptime_s
  ) values (
    p_host,
    (v_s ->> 'cpu_pct')::real,
    (v_s ->> 'load1')::real,
    (v_s ->> 'mem_total')::bigint,
    (v_s ->> 'mem_used')::bigint,
    (v_s ->> 'mem_available')::bigint,
    (v_s ->> 'swap_total')::bigint,
    (v_s ->> 'swap_used')::bigint,
    case when jsonb_typeof(v_s -> 'disk') = 'array' then v_s -> 'disk' end,
    (v_s ->> 'net_rx_bps')::real,
    (v_s ->> 'net_tx_bps')::real,
    case when jsonb_typeof(v_s -> 'connections') = 'object' then v_s -> 'connections' end,
    case when jsonb_typeof(v_s -> 'services') = 'array' then v_s -> 'services' end,
    (v_s ->> 'uptime_s')::bigint
  );

  update public.monitor_hosts
     set last_seen = now(),
         info = case when jsonb_typeof(v_s -> 'info') = 'object' then v_s -> 'info' else info end
   where id = p_host;

  delete from public.host_metrics where host_id = p_host and at < now() - interval '7 days';
  return jsonb_build_object('ok', true);
end;
$$;

-- Admin: hosts with latest sample + history for charts.
create or replace function public.admin_host_metrics(p_minutes int default 60)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_window interval := make_interval(mins => greatest(5, least(coalesce(p_minutes, 60), 10080)));
  v_bucket int := case
                    when coalesce(p_minutes, 60) <= 60 then 30
                    when p_minutes <= 360 then 120
                    when p_minutes <= 1440 then 600
                    else 3600 end;
begin
  perform public._admin_guard();
  return jsonb_build_object(
    'hosts', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', h.id, 'name', h.name, 'role', h.role, 'info', h.info,
               'last_seen', h.last_seen,
               'online', h.last_seen > now() - interval '2 minutes',
               'latest', (select to_jsonb(m) - 'id' - 'host_id' from public.host_metrics m
                           where m.host_id = h.id order by m.at desc limit 1),
               'series', coalesce((
                 select jsonb_agg(jsonb_build_object(
                          'at', b.bucket, 'cpu', round(b.cpu::numeric, 1), 'mem', round(b.mem::numeric, 1),
                          'rx', round(b.rx::numeric), 'tx', round(b.tx::numeric), 'conn', b.conn
                        ) order by b.bucket)
                   from (
                     select to_timestamp(floor(extract(epoch from m.at) / v_bucket) * v_bucket) as bucket,
                            avg(m.cpu_pct) as cpu,
                            avg(100.0 * m.mem_used / nullif(m.mem_total, 0)) as mem,
                            avg(m.net_rx_bps) as rx,
                            avg(m.net_tx_bps) as tx,
                            max((m.connections ->> 'established')::int) as conn
                       from public.host_metrics m
                      where m.host_id = h.id and m.at > now() - v_window
                      group by 1
                   ) b), '[]'::jsonb)
             ) order by h.name)
        from public.monitor_hosts h), '[]'::jsonb),
    'bucket_seconds', v_bucket,
    'generated_at', now()
  );
end;
$$;

-- Admin: register a host and get its ingest token (shown once).
create or replace function public.admin_monitor_host_create(p_id text, p_name text, p_role text default null)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public, extensions
as $$
declare
  v_token text := encode(gen_random_bytes(24), 'hex');
begin
  perform public._admin_guard();
  insert into public.monitor_hosts (id, name, role, token_hash)
  values (p_id, p_name, p_role, encode(digest(v_token, 'sha256'), 'hex'))
  on conflict (id) do update
    set name = excluded.name, role = excluded.role, token_hash = excluded.token_hash;
  perform public._admin_audit('monitor.host.token', p_id, '{}'::jsonb);
  return jsonb_build_object('id', p_id, 'token', v_token);
end;
$$;

create or replace function public.admin_monitor_host_delete(p_id text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public
as $$
begin
  perform public._admin_guard();
  delete from public.monitor_hosts where id = p_id;
  perform public._admin_audit('monitor.host.delete', p_id, '{}'::jsonb);
  return jsonb_build_object('deleted', true);
end;
$$;

revoke all on function public.ingest_host_metrics(text, text, jsonb) from public;
revoke all on function public.admin_host_metrics(int) from public;
revoke all on function public.admin_monitor_host_create(text, text, text) from public;
revoke all on function public.admin_monitor_host_delete(text) from public;
grant execute on function public.ingest_host_metrics(text, text, jsonb) to anon, authenticated;
grant execute on function public.admin_host_metrics(int) to authenticated;
grant execute on function public.admin_monitor_host_create(text, text, text) to authenticated;
grant execute on function public.admin_monitor_host_delete(text) to authenticated;

notify pgrst, 'reload schema';
