create extension if not exists pgcrypto;

-- ---------- Profiles (mirrors auth.users) ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  display_name text,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own"
  on public.profiles for select
  using (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own"
  on public.profiles for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- Papers (archive metadata) ----------
create table if not exists public.papers (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  subject text not null,
  year int,
  paper_type text,
  questions_count int,
  file_size text,
  file_url text,
  description text,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.papers enable row level security;

drop policy if exists "papers_public_read" on public.papers;
create policy "papers_public_read"
  on public.papers for select
  using (published = true);

-- Writes intentionally have no anon policy: add papers from the
-- Supabase dashboard / service role, or from your own admin tooling.

-- ---------- Download history ----------
create table if not exists public.downloads (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  paper_id text,
  paper_title text,
  created_at timestamptz not null default now()
);

alter table public.downloads enable row level security;

drop policy if exists "downloads_insert_own" on public.downloads;
create policy "downloads_insert_own"
  on public.downloads for insert
  with check (auth.uid() = user_id);

drop policy if exists "downloads_select_own" on public.downloads;
create policy "downloads_select_own"
  on public.downloads for select
  using (auth.uid() = user_id);

