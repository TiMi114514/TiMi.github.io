create or replace function public.admin_analytics(p_days int default 7)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_days int := greatest(coalesce(p_days, 7), 1);
  v_start timestamptz := now() - make_interval(days => v_days);
  v_prev_start timestamptz := v_start - make_interval(days => v_days);
  v_result jsonb;
begin
  if not public.is_admin() then
    raise exception 'not authorized';
  end if;

  with filtered as (
    select * from public.page_views where created_at >= v_start
  ),
  previous as (
    select * from public.page_views
    where created_at >= v_prev_start and created_at < v_start
  ),
  sessions as (
    select coalesce(user_id::text, session_id) as sid,
           min(created_at) as started,
           max(created_at) as ended
    from filtered
    group by 1
  ),
  prev_sessions as (
    select coalesce(user_id::text, session_id) as sid,
           min(created_at) as started,
           max(created_at) as ended
    from previous
    group by 1
  ),
  totals as (
    select
      (select count(*) from filtered) as visits,
      (select count(*) from sessions) as uniques,
      coalesce((select avg(extract(epoch from (ended - started))) from sessions), 0) as duration,
      (select count(*) from previous) as prev_visits,
      (select count(*) from prev_sessions) as prev_uniques,
      coalesce((select avg(extract(epoch from (ended - started))) from prev_sessions), 0) as prev_duration,
      (select count(*) from public.live_presence
        where last_seen >= now() - interval '2 minutes') as live
  ),
  series as (
    select d::date as day, count(f.id) as visits
    from generate_series(v_start::date, now()::date, interval '1 day') d
    left join filtered f on f.created_at::date = d::date
    group by 1
    order by 1
  ),
  pages as (
    select path, count(*) as visits
    from filtered
    group by 1
    order by 2 desc
    limit 8
  ),
  countries as (
    select coalesce(country, 'Unknown') as country, count(*) as visits
    from filtered
    group by 1
    order by 2 desc
    limit 6
  )
  select jsonb_build_object(
    'days', v_days,
    'total_visits', totals.visits,
    'unique_visitors', totals.uniques,
    'avg_duration', round(totals.duration)::int,
    'prev_total_visits', totals.prev_visits,
    'prev_unique_visitors', totals.prev_uniques,
    'prev_avg_duration', round(totals.prev_duration)::int,
    'live_visitors', totals.live,
    'series', coalesce((select jsonb_agg(jsonb_build_object('date', day, 'visits', visits)) from series), '[]'::jsonb),
    'pages', coalesce((select jsonb_agg(jsonb_build_object('path', path, 'visits', visits)) from pages), '[]'::jsonb),
    'countries', coalesce((select jsonb_agg(jsonb_build_object('country', country, 'visits', visits)) from countries), '[]'::jsonb)
  )
  into v_result
  from totals;

  return v_result;
end;
$$;

revoke all on function public.admin_analytics(int) from public;
grant execute on function public.admin_analytics(int) to authenticated;

create or replace function public.admin_list_users()
returns table (
  id uuid,
  email text,
  display_name text,
  created_at timestamptz,
  last_sign_in_at timestamptz,
  confirmed boolean
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'not authorized';
  end if;

  return query
    select u.id,
           u.email::text,
           coalesce(p.display_name, ''),
           u.created_at,
           u.last_sign_in_at,
           (u.email_confirmed_at is not null)
    from auth.users u
    left join public.profiles p on p.id = u.id
    order by u.created_at desc
    limit 200;
end;
$$;

